--    Flow: demand_order -> do_request -> (approve) -> do_received
-- =============================================================================

CREATE TABLE demand_order (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date        date    NOT NULL,
    from_branch integer NOT NULL REFERENCES branch(id),
    to_branch   integer NOT NULL REFERENCES branch(id),
    type        text,        -- 'RAW' | 'FINISH'
    status      text,
    note        text,
    gross       numeric(18,2) NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    created_by  integer NOT NULL DEFAULT 0,
    updated_by  integer NOT NULL DEFAULT 0
);

CREATE TABLE demand_order_detail (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
