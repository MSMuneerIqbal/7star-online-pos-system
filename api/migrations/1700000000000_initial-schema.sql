-- -----------------------------------------------------------------------------
-- GENERAL LEDGER
-- Legacy column order (recovered from positional INSERTs, NOT from the C# class):
--   Date, Datetime, InvId, Vtype, Dr, Cr, AccountId, Detail, VoucherNo,
--   TransId, BranchId
-- The ETL must map by this order, not by the model property order.
--
-- trans_id groups the legs of one balanced voucher. The CHECK below is what the
-- legacy system lacked: it rejects a leg that is neither a debit nor a credit.
-- Per-voucher balance is enforced in the application layer (see §NOTE).
-- -----------------------------------------------------------------------------
CREATE TABLE transactions (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date       date          NOT NULL,
    datetime   timestamptz   NOT NULL DEFAULT now(),
    inv_id     integer       NOT NULL DEFAULT 0,
    vtype      text          NOT NULL,   -- SINV, PINV, SRET, PRET, CRV, CPV, BRV, BPV, JV
    dr         numeric(18,2) NOT NULL DEFAULT 0,
    cr         numeric(18,2) NOT NULL DEFAULT 0,
    account_id integer       NOT NULL REFERENCES account(account_id),
    detail     text,
    voucher_no integer       NOT NULL,
    trans_id   integer       NOT NULL,
    branch_id  integer       NOT NULL DEFAULT 0 REFERENCES branch(id),
    CONSTRAINT chk_transactions_one_sided CHECK (dr >= 0 AND cr >= 0 AND (dr = 0) <> (cr = 0))
);
CREATE INDEX idx_transactions_account_date ON transactions(account_id, date);
CREATE INDEX idx_transactions_voucher      ON transactions(trans_id);
CREATE INDEX idx_transactions_source       ON transactions(vtype, inv_id);
CREATE INDEX idx_transactions_branch_date  ON transactions(branch_id, date);

-- Replaces "SELECT ISNULL(MAX(TransId),0)+1" — that was a race condition.
CREATE SEQUENCE transactions_trans_id_seq AS integer START 1;
CREATE SEQUENCE transactions_voucher_no_seq AS integer START 1;

