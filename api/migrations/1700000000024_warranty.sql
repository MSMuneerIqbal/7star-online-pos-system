-- Up Migration
--
-- PHASE 9 — warranty. (PLAN.md Phase 9, SPECS §10, PRINCIPLES §8)
--
-- The customer never waits: the branch hands over a replacement from its own
-- stock immediately, the faulty unit sits in Warranty Hold (not sellable), and
-- the branch raises a claim the warehouse assesses. The branch is never charged;
-- the warehouse carries the cost as a warranty expense. Either outcome returns
-- to the branch that claimed it, graded Repaired (same unit) or New (a new
-- battery), restoring branch stock.

-- =============================================================================
-- 1. Warranty hold — faulty units at a branch, not sellable, not in stock value
-- =============================================================================

CREATE TABLE warranty_hold (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id   integer NOT NULL REFERENCES branch(id),
    product_id  integer NOT NULL REFERENCES product(id),
    qty         numeric(18,3) NOT NULL DEFAULT 0,
    date        date NOT NULL,
    note        text,
    status      text NOT NULL DEFAULT 'HELD',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    created_by  integer NOT NULL DEFAULT 0,
    updated_by  integer NOT NULL DEFAULT 0,
    CONSTRAINT warranty_hold_status_check CHECK (status IN ('HELD', 'CLAIMED'))
);

-- =============================================================================
-- 2. Warranty claim — branch -> warehouse
-- =============================================================================

CREATE TABLE warranty_claim (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_number  text NOT NULL,
    branch_id   integer NOT NULL REFERENCES branch(id),
    warehouse_branch_id integer REFERENCES branch(id),
    date        date NOT NULL,
    status      text NOT NULL DEFAULT 'RAISED',
    note        text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    created_by  integer NOT NULL DEFAULT 0,
    updated_by  integer NOT NULL DEFAULT 0,
    CONSTRAINT warranty_claim_status_check
        CHECK (status IN ('RAISED', 'ASSESSED', 'CLOSED'))
);

CREATE UNIQUE INDEX idx_warranty_claim_doc_number ON warranty_claim (branch_id, doc_number);

CREATE TABLE warranty_claim_detail (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    integer NOT NULL REFERENCES warranty_claim(id) ON DELETE CASCADE,
    product_id  integer NOT NULL REFERENCES product(id),
    qty         numeric(18,3) NOT NULL DEFAULT 0,
    assessment  text,
    outcome     text,
    grade       text,
    CONSTRAINT warranty_claim_detail_assessment_check
        CHECK (assessment IS NULL OR assessment IN ('REPAIRABLE', 'NOT_REPAIRABLE')),
    CONSTRAINT warranty_claim_detail_outcome_check
        CHECK (outcome IS NULL OR outcome IN ('RETURNED_REPAIRED', 'REPLACED_NEW'))
);

-- Raw parts consumed repairing a claimed unit.
CREATE TABLE warranty_part (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id    integer NOT NULL REFERENCES warranty_claim(id) ON DELETE CASCADE,
    pid         integer NOT NULL,
    pname       text,
    qty         numeric(18,3) NOT NULL DEFAULT 0,
    price       numeric(18,2) NOT NULL DEFAULT 0,
    total       numeric(18,2) NOT NULL DEFAULT 0
);

